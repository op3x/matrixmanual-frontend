// Writes config.js from MANUALOS_API_BASE. The value must be an http(s) origin.
// Production deploys pass the production origin explicitly. This script does not
// invent one, and it stores the origin only (no userinfo, path, or query).
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const raw = String(process.env.MANUALOS_API_BASE || '').trim();
let origin = '';
try {
  const url = new URL(raw);
  if (url.protocol !== 'http:' && url.protocol !== 'https:') throw new Error('protocol');
  if (!url.hostname) throw new Error('host');
  origin = url.origin;
} catch {
  console.error('MANUALOS_API_BASE must be an http or https URL');
  process.exit(1);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const body = [
  '// Generated by dev/write-config.mjs. Do not put secrets in this file.',
  '// Production deploys set MANUALOS_API_BASE to the production origin.',
  'window.MANUALOS_API_BASE = ' + JSON.stringify(origin) + ';',
  '',
].join('\n');

await writeFile(path.join(root, 'config.js'), body);
console.log('Wrote config.js ' + origin);
